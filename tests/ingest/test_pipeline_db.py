"""The DB Agent end to end, against a source database built for the test.

The demo tenants are generated by `scripts.demo_company`, which is the same generator
the product demo uses — so these tests exercise the real path rather than a fixture of
it, and a change that breaks the demo breaks the suite first.
"""

